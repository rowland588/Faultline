#!/usr/bin/env node
/* THE LIST OF TOOLS WITHOUT A GUIDE, regenerated (src/catalogue/guide.ts; docs/METHODS.md §15).
 *
 *   node scripts/guides-exempt.mjs            rewrite src/catalogue/guides/exempt.ts from the catalogue and the guides
 *   node scripts/guides-exempt.mjs --check    say what it would write, change nothing
 *
 * An available or part-built entry is without a guide when neither it nor the tool it is a mode of (up the chain) has one. The
 * guides are read from guides/*.ts by their keys (`  'FC-094': {` at two spaces); the catalogue by esbuild, as catalogue.mjs does. */
import { build } from 'esbuild';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = await build({
  stdin: { contents: "export { ENTRIES } from './src/catalogue/index.ts';", resolveDir: ROOT, loader: 'ts', sourcefile: 'exempt-cli.ts' },
  bundle: true, write: false, format: 'esm', platform: 'node', logLevel: 'silent',
});
const { ENTRIES } = await import(`data:text/javascript;base64,${Buffer.from(out.outputFiles[0].text).toString('base64')}`);

const dir = join(ROOT, 'src/catalogue/guides');
const has = new Set();
for (const f of readdirSync(dir).filter(f => f.endsWith('.ts') && f !== 'exempt.ts')) {
  for (const m of readFileSync(join(dir, f), 'utf8').matchAll(/^ {2}'(FC-\d+)': \{/gm)) has.add(m[1]);
}
const byId = new Map(ENTRIES.map(e => [e.id, e]));
const covered = id => { let at = id; for (let hop = 0; at && hop < 4; hop++) { if (has.has(at)) return true; at = byId.get(at)?.partOf; } return false; };
const live = ENTRIES.filter(e => e.status === 'available' || e.status === 'partial');
const exempt = live.filter(e => !covered(e.id)).map(e => e.id).sort();

const rows = []; for (let i = 0; i < exempt.length; i += 8) rows.push(`  ${exempt.slice(i, i + 8).map(id => `'${id}'`).join(', ')},`);
const file = `/* TOOLS WITHOUT A GUIDE YET — generated by scripts/guides-exempt.mjs, never by hand.
 * Every available or part-built tool must carry a guide (src/catalogue/guide.ts): what each step means, what to do, what
 * you get. This list is what was not written when the rule began. __tests__/guides.test.ts holds it true both ways: a tool
 * with a guide may not stay on it, and a tool without one that is not on it fails. A new tool is never added here — it is
 * built with its guide. When this list is empty, delete it and the test holds the rule with no exceptions. */
export const GUIDE_EXEMPT: readonly string[] = [${rows.length ? `\n${rows.join('\n')}\n` : ''}];
`;
if (process.argv.includes('--check')) process.stdout.write(file);
else writeFileSync(join(dir, 'exempt.ts'), file);
console.log(`exempt: ${exempt.length} of ${live.length} available or partial`);
